pub fn prometheus(status:&Value)->String{
    let mut lines=vec!["# HELP justfit_info JustFit runtime metrics.".into(),"# TYPE justfit_info gauge".into(),"justfit_info{runtime=\"native\"} 1".into()];
    for state in ["normal","warning","critical"]{lines.push(format!("justfit_memory_pressure{{state=\"{state}\"}} {}",u8::from(status["memory_pressure"].as_str()==Some(state))))}
    for(name,path)in SERIES{
        let mut value=status;for key in *path{value=&value[*key];}
        let number=match value{Value::Bool(v)=>Some(u8::from(*v).to_string()),Value::Number(v) if v.as_f64().is_some_and(f64::is_finite)=>Some(v.to_string()),_=>None};
        if let Some(value)=number{lines.push(format!("{name} {value}"))}
    }
    for stage in super::latency::STAGES{
        let values=&status["latency"][stage];if values.is_null(){continue}
        let name=format!("justfit_{stage}_seconds");lines.push(format!("# TYPE {name} histogram"));
        for bound in super::latency::BUCKETS.iter().map(|(label,_)|*label).chain(std::iter::once("+Inf")){let count=&values["buckets"][bound];lines.push(format!("{name}_bucket{{le=\"{bound}\"}} {count}"))}
        lines.push(format!("{name}_count {}",values["count"]));lines.push(format!("{name}_sum {}",values["sum"]));
    }
    lines.join("\n")+"\n"
}
